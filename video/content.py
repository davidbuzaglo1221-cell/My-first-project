def build_timeline():
    segs = [("intro", 0.0, INTRO, None)]
    t = INTRO
    for i, tip in enumerate(TIPS, 1):
        segs.append(("tip", t, TIP, dict(tip, n=i)))
        t += TIP
        if i in INTER_AFTER:
            segs.append(("inter", t, INTER, dict(INTERS[i], n=i)))
            t += INTER
    segs.append(("outro", t, OUTRO, None))
    t += OUTRO
    return segs, t


SEGMENTS, TOTAL = build_timeline()


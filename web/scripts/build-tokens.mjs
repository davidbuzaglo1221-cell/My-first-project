// Generates src/styles/tokens.css from replica/design/tokens.json and tokens.dark.json.
// The JSON files are the source of truth (checked by contrast.py); never edit tokens.css by hand.
//   node scripts/build-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const designDir = resolve(root, "../replica/design");
const light = JSON.parse(readFileSync(resolve(designDir, "tokens.json"), "utf8"));
const dark = JSON.parse(readFileSync(resolve(designDir, "tokens.dark.json"), "utf8"));

const colorVars = (colors) =>
  Object.entries(colors).map(([name, value]) => `  --c-${name}: ${value};`).join("\n");

const missing = Object.keys(light.color).filter((k) => !(k in dark.color));
if (missing.length) {
  throw new Error(`tokens.dark.json is missing roles: ${missing.join(", ")}`);
}

const typeVars = Object.entries(light.type)
  .map(([name, t]) =>
    [
      `  --text-${name}: ${t.size / 16}rem;`,
      `  --text-${name}--line-height: ${t.line / t.size};`,
      `  --text-${name}--font-weight: ${t.weight};`,
    ].join("\n"),
  )
  .join("\n");

const radiusVars = Object.entries(light.radius)
  .map(([name, px]) => `  --radius-${name}: ${px === 999 ? "9999px" : `${px / 16}rem`};`)
  .join("\n");

const shadowVars = Object.entries(light.shadow)
  .map(([name, v]) => `  --shadow-${name}: ${v};`)
  .join("\n");

const layoutVars = Object.entries(light.layout)
  .map(([name, px]) => `  --layout-${name}: ${px / 16}rem;`)
  .join("\n");

// Tailwind theme: utilities read the runtime variables, so switching theme needs no rebuild.
const themeColors = Object.keys(light.color)
  .map((name) => `  --color-${name}: var(--c-${name});`)
  .join("\n");

const css = `/* Generated by scripts/build-tokens.mjs from replica/design/tokens*.json. Do not edit. */

:root {
  color-scheme: light;
${colorVars(light.color)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${colorVars(dark.color).replace(/^/gm, "  ")}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${colorVars(dark.color)}
}

@theme inline {
  --color-*: initial;
  --color-transparent: transparent;
  --color-current: currentColor;
${themeColors}
  --font-sans: "Heebo Variable", ${light.font.sans.replace(/^Heebo,\s*/, "")};
${typeVars}
${radiusVars}
${shadowVars}
  --spacing: 0.25rem;
  --ease-out: ${light.motion.ease};
  --default-transition-duration: ${light.motion.base};
}

:root {
${layoutVars}
  --motion-fast: ${light.motion.fast};
  --motion-base: ${light.motion.base};
  --motion-slow: ${light.motion.slow};
}
`;

const out = resolve(root, "src/styles/tokens.css");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`wrote ${out} (${Object.keys(light.color).length} colour roles, light + dark)`);

import type { Domain } from "@/data/life-types";

// The academy: three lessons for each of the nine areas, written for this app. Each one opens with
// a hook, teaches in three short parts, ends with three points to keep and one thing to do today.
// Claims stay to what the evidence supports; where a study is named it is real and its size is not
// inflated. The same text is what the narrator reads, so it is written to be heard as well as read.

export type AcademyLesson = {
  id: string;
  domain: Domain;
  /** 1..3 within the area: foundations, method, mastery. */
  n: 1 | 2 | 3;
  title: string;
  hook: string;
  parts: { h: string; p: string }[];
  keep: string[];
  practice: string;
};

const L = (id: string, domain: Domain, n: 1 | 2 | 3, title: string, hook: string, parts: [string, string][], keep: string[], practice: string): AcademyLesson => ({
  id,
  domain,
  n,
  title,
  hook,
  parts: parts.map(([h, p]) => ({ h, p })),
  keep,
  practice,
});


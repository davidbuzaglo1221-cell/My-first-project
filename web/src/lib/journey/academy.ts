export const ACADEMY_BY_ID = new Map(ACADEMY.map((l) => [l.id, l]));

/** The whole lesson as one text, the way it is read aloud. */
export function narration(l: AcademyLesson): string {
  return [l.title + ".", l.hook, ...l.parts.flatMap((p) => [p.h + ".", p.p]), "שלושה דברים לזכור.", ...l.keep.map((k) => k + "."), "המשימה להיום.", l.practice].join("\n\n");
}

/** Minutes to read, at a comfortable pace (about 150 Hebrew words a minute aloud). */
export function minutesOf(l: AcademyLesson): number {
  return Math.max(1, Math.ceil(narration(l).split(/\s+/).length / 140));
}

/** The next lesson to take: the first unread one in today's area, else the first unread anywhere. */
export function nextLesson(read: Set<string>, domain?: Domain): AcademyLesson {
  return ACADEMY.find((l) => l.domain === domain && !read.has(l.id)) ?? ACADEMY.find((l) => !read.has(l.id)) ?? ACADEMY.find((l) => l.domain === domain) ?? ACADEMY[0];
}

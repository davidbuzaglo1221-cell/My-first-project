const { chromium } = require('playwright')
;(async () => {
  const S = process.argv[2]
  const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] })
  const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
  await p.addInitScript(() => { try { sessionStorage.setItem("hasifria:opened", "1") } catch {} }) // the opening is tested on its own
  const errs = []; p.on('pageerror', (e) => errs.push(e.message))
  await p.addInitScript(() => localStorage.setItem('ascend:v1', JSON.stringify({ v: 1, onboarded: true })))
  await p.goto('http://localhost:4173/#/book/atomic-habits'); await p.waitForTimeout(800)
  await p.click('.bhero__actions .btn--primary'); await p.waitForTimeout(500)
  await p.evaluate(() => history.back()); await p.waitForTimeout(600)
  await p.screenshot({ path: S + '/pl-mini.png' })
  await p.click('.mini2__open'); await p.waitForTimeout(4000)
  await p.screenshot({ path: S + '/pl-art.png' })
  await p.click('.np2__tool[aria-label="כתוביות"]'); await p.waitForTimeout(1500)
  await p.screenshot({ path: S + '/pl-lyrics.png' })
  await p.click('.np2__tool[aria-label="הבא בתור"]'); await p.waitForTimeout(800)
  await p.screenshot({ path: S + '/pl-queue.png' })
  const before = await p.evaluate(() => window.__ascend.player.get().track.id)
  await p.click('.np2__t[aria-label="פרק הבא"]'); await p.waitForTimeout(1500)
  const after = await p.evaluate(() => window.__ascend.player.get().track.id)
  console.log('next chapter', before, '->', after, 'errors', errs)
  await b.close()
})()

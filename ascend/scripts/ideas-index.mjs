// Regenerates src/content/ideas/index.ts from the per-book idea files (one file per book).
import { readdirSync, writeFileSync } from 'node:fs'
const files = readdirSync('src/content/ideas').filter((f) => f.endsWith('.ts') && f !== 'index.ts' && f !== 'parse.ts').map((f) => f.replace(/\.ts$/, '')).sort()
const v = (f) => '_' + f.replace(/[^a-z0-9]/gi, '_')
writeFileSync('src/content/ideas/index.ts', `/* Generated by scripts/ideas-index.mjs: the key ideas of every chapter, in depth. */
import { parseIdeas } from './parse'
${files.map((f) => `import ${v(f)} from './${f}'`).join('\n')}

export const chapterIdeas = parseIdeas([${files.map(v).join(', ')}])
`)
console.log(files.length, 'books with key ideas')

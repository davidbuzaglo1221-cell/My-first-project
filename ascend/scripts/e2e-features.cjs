const { chromium } = require('playwright')
const ok = (c, m) => console.log((c ? 'PASS ' : 'FAIL ') + m)
;(async () => {
  const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] })
  const p = await b.newPage({ viewport: { width: 390, height: 844 } })
  await p.addInitScript(() => { try { sessionStorage.setItem("hasifria:opened", "1") } catch {} }) // the opening is tested on its own
  const errs = []; p.on('pageerror', (e) => errs.push(e.message))
  const S = () => p.evaluate(() => window.__ascend.store.get())
  await p.goto('http://localhost:4173/#/')
  await p.waitForTimeout(800)
  // 1. welcome: no questions, one button
  ok(await p.locator('.opening__enter >> nth=0').isVisible(), 'opening: a single entry button')
  ok((await p.locator('.opening .owall__row .cover').count()) === 102, 'opening: the whole library (51 covers) inside the tour')
  ok((await p.locator('.opening input, .opening [role=radio]').count()) === 0, 'opening asks nothing')
  ok(await p.locator('.ophero__pano img').isVisible() && (await p.locator('.opin').count()) === 5, 'entrance: the house in full, and five worlds waiting inside')
  ok(await p.evaluate(() => { const i = document.querySelector('.ophero__pano img'); return i.complete && i.naturalWidth > 2000 }), 'entrance photo loaded in full resolution')
  await p.click('.opvoice'); await p.waitForTimeout(2500)
  ok(await p.locator('.opvoice.is-on').isVisible(), "entrance: David's voice plays")
  const prog = await p.evaluate(() => getComputedStyle(document.querySelector('.opvoice__btn')).getPropertyValue('--p'))
  ok(parseFloat(prog) > 2, 'entrance: voice progress moves (' + prog.trim() + ')')
  await p.click('.opvoice'); await p.waitForTimeout(300)
  ok(!(await p.locator('.opvoice.is-on').count()), 'entrance: voice pauses')
  await p.click('.opening__enter >> nth=0'); await p.waitForTimeout(900)
  ok(await p.locator('h1:has-text("המסע שלך")').isVisible(), 'enters the home library')
  // 2. library: search + filters
  await p.goto('http://localhost:4173/#/explore'); await p.waitForTimeout(600)
  await p.fill('input[type=search]', 'הרגל'); await p.waitForTimeout(300)
  const n1 = await p.locator('.tile').count(); ok(n1 > 0 && n1 < 20, `search "הרגל" finds ${n1} books`)
  await p.fill('input[type=search]', ''); await p.click('.chips .chip:has-text("כסף")'); await p.waitForTimeout(300)
  ok((await p.locator('.tile').count()) === 5, 'topic chip filters to the 5 money books')
  await p.click('.filterbtn'); await p.waitForTimeout(400); await p.click('.sheet .chip:has-text("הקצרים קודם")'); await p.click('.sheet .btn--primary'); await p.waitForTimeout(400)
  ok(await p.locator('.filterbtn b').isVisible(), 'filter sheet sets a sort and shows the badge')
  // 3. reader: love a paragraph, add note, chapter counts when read
  await p.goto('http://localhost:4173/#/read/atomic-habits'); await p.waitForTimeout(700)
  await p.locator('.rpara p').first().click(); await p.click('.rpara__bar button:has-text("אהבתי")'); await p.waitForTimeout(300)
  ok((await S()).notes?.some((n) => n.kind === 'love'), 'paragraph saved to loved')
  await p.evaluate(() => window.scrollTo(0, document.body.scrollHeight)); await p.waitForTimeout(800)
  ok(!!(await S()).readDone?.['atomic-habits-1'], 'reading a chapter to the end counts it as learned')
  // 4. book page shows percent
  await p.goto('http://localhost:4173/#/book/atomic-habits'); await p.waitForTimeout(600)
  const pct = await p.locator('.learnbox__pct').innerText(); ok(pct !== '0%', `book shows learned ${pct}`)
  // 5. quiz: answer all, score saved
  await p.goto('http://localhost:4173/#/quiz/atomic-habits'); await p.waitForTimeout(600)
  for (let i = 0; i < 12; i++) {
    if (!(await p.locator('.opt').count())) break
    await p.locator('.opt').first().click(); await p.waitForTimeout(120)
    await p.locator('.quiz__foot .btn').click(); await p.waitForTimeout(150)
  }
  ok(await p.locator('.quiz__ring').isVisible(), 'quiz finishes with a score')
  ok((await S()).quiz?.['book:atomic-habits'] !== undefined, 'quiz score saved')
  // 6. notebook: add a note, cards due
  await p.goto('http://localhost:4173/#/notes'); await p.waitForTimeout(500)
  await p.click('.nb__tools .btn--primary'); await p.fill('.note-input', 'פתק בדיקה'); await p.click('.sheet .btn--primary:has-text("שמור")'); await p.waitForTimeout(300)
  ok(await p.locator('.note__text:has-text("פתק בדיקה")').isVisible(), 'note added and listed')
  await p.click('.tabs__t:has-text("לזכור")'); await p.waitForTimeout(300)
  ok(await p.locator('.flash').isVisible(), 'memory card due for the learned chapter')
  await p.click('.flash'); await p.click('.cards__grade .btn--primary'); await p.waitForTimeout(200)
  ok(((await S()).cards?.['atomic-habits-1']?.box ?? 0) === 1, 'card graded and scheduled')
  await p.click('.tabs__t:has-text("תזכורות")'); await p.locator('.chips .chip').first().click(); await p.waitForTimeout(200)
  ok(((await S()).reminders ?? []).length === 1, 'reminder added')
  // 7. freedom: meditation plays from its file
  await p.goto('http://localhost:4173/#/freedom'); await p.waitForTimeout(600)
  await p.click('.fr-lead'); await p.waitForTimeout(3000)
  const pl = await p.evaluate(() => { const s = window.__ascend.player.get(); return { id: s.track?.id, st: s.status, pos: s.position, d: s.duration, segs: s.segments.length } })
  ok(pl.id === 'calm:freedom' && pl.st === 'playing' && pl.d > 200 && pl.segs > 15, `meditation plays ${JSON.stringify(pl)}`)
  await p.evaluate(() => window.__ascend.pause())
  // 8. breathing trainer runs
  await p.goto('http://localhost:4173/#/breathe/box'); await p.waitForTimeout(400)
  await p.click('.breathe__actions .btn--primary'); await p.waitForTimeout(5000)
  ok((await p.locator('.orb__text strong').innerText()) === 'החזק', 'breathing moves from inhale to hold after 4 seconds')
  // 9. progress shows the books
  await p.goto('http://localhost:4173/#/progress'); await p.waitForTimeout(500)
  ok((await p.locator('.bprog').count()) >= 1, 'progress lists learned books')
  // 10. your day + thirty-day program: play today's practice to the end, the day counts everywhere
  await p.goto('http://localhost:4173/#/'); await p.waitForTimeout(700)
  ok((await p.locator('.myday__list li').count()) === 3, 'home: your day has three steps')
  ok((await p.locator('.myday__challenge').innerText()).length > 20, 'home: a challenge of the day')
  await p.locator('.myday__list li').first().locator('button').click(); await p.waitForTimeout(2000)
  const day = await p.evaluate(() => window.__ascend.player.get())
  ok(day.track?.id?.startsWith('calm:day-') && day.status === 'playing' && day.duration > 60, `program day plays (${day.track?.id}, ${Math.round(day.duration)}s)`)
  await p.evaluate(() => window.__ascend.seek(window.__ascend.player.get().duration - 1.5)); await p.waitForTimeout(3500)
  ok(Object.keys((await S()).program ?? {}).length >= 1, 'finishing a program day records it')
  await p.goto('http://localhost:4173/#/freedom'); await p.waitForTimeout(600)
  ok((await p.locator('.prog__grid li').count()) === 30 && (await p.locator('.prog__grid .is-done').count()) >= 1, 'freedom: thirty days, finished day marked')
  const ics = await p.evaluate(() => fetch('remind/2030.ics').then((r) => r.text()))
  ok(ics.startsWith('BEGIN:VCALENDAR') && (ics.match(/BEGIN:VEVENT/g) || []).length === 120 && ics.includes('BEGIN:VALARM'), 'daily reminder calendar: 120 days with alerts')
  // situations, check-in and notifications
  await p.goto('http://localhost:4173/#/'); await p.waitForTimeout(700)
  ok((await p.locator('.myday__more button').count()) === 2, 'your day: two doors (situation, check-in)')
  await p.click('.myday__more button >> nth=0'); await p.waitForTimeout(500)
  ok(await p.locator('h1:has-text("מה היית עושה?")').isVisible(), 'situation of the day opens')
  await p.locator('.sit__choices button').first().click(); await p.waitForTimeout(300)
  ok((await p.locator('.sit__why').count()) >= 1 && Object.keys((await S()).situations || {}).length === 1, 'choosing reveals why and is saved')
  await p.click('text=עוד מצב אחד'); await p.waitForTimeout(400)
  ok((await p.locator('.sit__choices button:not([disabled])').count()) === 3, 'another situation is fresh')
  await p.goto('http://localhost:4173/#/checkin'); await p.waitForTimeout(500)
  await p.click('.ck__mood >> nth=3'); await p.fill('.ck__q textarea', 'יום טוב'); await p.click('.ck__q .btn'); await p.waitForTimeout(300)
  ok(Object.values((await S()).checkins || {})[0]?.mood === 4, 'check-in saves mood and answer')
  ok((await p.locator('.ck__entry').count()) === 1, 'check-in shows in history')
  await p.goto('http://localhost:4173/#/'); await p.waitForTimeout(600)
  await p.click('.myday__remind'); await p.waitForTimeout(500)
  ok(await p.locator('.sheet button:has-text("הפעל התראות")').isVisible() && (await p.locator('.sheet .chip').count()) === 8, 'notification sheet: morning and evening hours')
  // tab bar: home, library, personal assistant, freedom, journey
  await p.keyboard.press('Escape'); await p.waitForTimeout(600)
  const tabs = await p.locator('.tabbar .tab span').allInnerTexts()
  ok(tabs.join('|') === 'בית|ספרייה|עוזר אישי|לחופש|המסע', 'tab bar: ' + tabs.join(' · '))
  await p.click('.tab--coach'); await p.waitForTimeout(500)
  ok((await p.evaluate(() => location.hash)) === '#/coach', 'assistant tab routes to the assistant')
  // every main screen leads with a photograph
  for (const r of ['/', '/explore', '/freedom', '/progress', '/coach', '/notes', '/situation', '/checkin', '/growth', '/settings', '/voices', '/library']) {
    await p.goto('http://localhost:4173/#' + r); await p.waitForTimeout(500)
    const ok2 = await p.evaluate(() => [...document.querySelectorAll('.view img')].some((i) => i.src.includes('/photos/') && i.getBoundingClientRect().top < 300))
    ok(ok2, 'photograph at the top of ' + r)
  }
  // coach: a full clarity session becomes a goal and a commitment, and the commitment can be closed
  await p.goto('http://localhost:4173/#/coach'); await p.waitForTimeout(700)
  ok(await p.locator('.cnote').first().isVisible(), 'coach: notices there is no goal yet')
  await p.click('.glist__row:has-text("בהירות")'); await p.waitForTimeout(500)
  for (const a of ['להכפיל את ההכנסה', 'חופש', 'מספר בבנק', 'דחיינות', 'לשלוח שלוש הודעות ללקוחות']) {
    await p.fill('.cq textarea', a); await p.click('.cnav .btn--primary'); await p.waitForTimeout(350)
  }
  ok(await p.locator('.cstep strong:has-text("לשלוח שלוש הודעות ללקוחות")').isVisible(), 'coach: session ends in one next step')
  await p.click('.cstep .btn--primary'); await p.waitForTimeout(600)
  const co = (await S()).coach
  ok(co?.goal?.text === 'להכפיל את ההכנסה' && co?.commits?.[0]?.status === 'open', 'coach: goal and commitment saved')
  await p.click('.glist__row:has-text("לשלוח שלוש")'); await p.waitForTimeout(500)
  await p.click('.sheet button:has-text("עשיתי")'); await p.waitForTimeout(500)
  ok((await S()).coach?.commits?.[0]?.status === 'done', 'coach: commitment marked done')
  await p.goto('http://localhost:4173/#/'); await p.waitForTimeout(600)
  ok(await p.locator('.nownext').isVisible() && await p.locator('.homehero__img').isVisible(), 'home: photograph and the one next action')
  ok(errs.length === 0, 'no page errors ' + errs.join(' | '))
  await b.close()
})()

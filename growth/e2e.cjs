// Runs dist/app.html in Chromium with a fake window.claude (db, user, sample, tts) and takes phone screenshots.
const { chromium } = require('playwright');
const fs = require('fs'); const path = require('path');
const page0 = fs.readFileSync(path.join(__dirname, 'dist', 'app.html'), 'utf8');
const html = `<!doctype html><html><head><meta charset=utf8><meta name=viewport content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style></head><body>${page0}</body></html>`;
const out = process.argv[2] || path.join(__dirname, 'shots'); fs.mkdirSync(out, { recursive: true });
const shot = (p, n) => p.screenshot({ path: path.join(out, n + '.png') });
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await p.addInitScript(() => {
    const store = {}; window.__spoken = []; window.__prompts = [];
    const db = { collection: (c) => ({ doc: (id) => ({ get: async () => ({ exists: !!store[c + '/' + id], data: () => store[c + '/' + id] }), set: async (d) => { store[c + '/' + id] = d; window.__saved = d; } }) }) };
    const reply = (prompt) => prompt.includes('צור משימה אישית') ? { topic: 'presence', task: 'שתי דקות של אנחה מחזורית לפני הפגישה.', why: 'נשיפה ארוכה מאטה את הדופק.' }
      : prompt.includes('נתח את תרגול') ? { score: 8, good: 'הבאת נתונים.', improve: 'לשתוק אחרי המספר.', line: 'על סמך התוצאות, אני מבקש 12 אחוז.', spoken: 'עבודה טובה.' }
      : { answer: 'כדי להתחיל לחסוך, תתחיל קטן. הוראת קבע של מאה שקל ביום אחרי המשכורת.', task: 'לקבוע הוראת קבע של מאה שקל.', remember: ['רוצה להתחיל לחסוך'] };
    const sample = Object.assign(async (msgs) => { window.__prompts.push(JSON.stringify(msgs)); return { text: 'אוקיי, תראה לי נתונים.' }; }, { json: async (prompt) => { window.__prompts.push(prompt); await new Promise(r => setTimeout(r, 150)); return reply(prompt); } });
    const tts = { speak: async (t) => { window.__spoken.push(t); await new Promise(r => setTimeout(r, 15)); }, stop() {}, onState() { return () => {}; } };
    const caps = { db, sample, tts, user: { id: async () => 'u1', isOwner: () => true } };
    window.claude = { use: async (n) => caps[n] ?? null };
  });
  await p.route('https://app.test/', r => r.fulfill({ contentType: 'text/html', body: html })); await p.goto('https://app.test/');
  await p.waitForTimeout(900); await shot(p, '01-welcome');
  await p.fill('#w-name', 'אורי'); await p.click('[data-focus=confidence]'); await p.click('[data-focus=faces]');
  await p.click('[data-act=start]'); await p.waitForTimeout(1200);
  await p.click('[data-act=close-player]');
  await shot(p, '02-home'); await p.screenshot({ path: path.join(out, '02b-home-full.png'), fullPage: true });
  await p.click('[data-act=check][data-k="0"]'); await p.waitForTimeout(300);
  await p.click('.burger'); await p.waitForTimeout(500); await shot(p, '03-drawer');
  await p.click('#drawer [data-arg=faces]'); await p.waitForTimeout(500); await shot(p, '04-topic');
  await p.click('.eps .ep >> nth=0'); await p.waitForSelector('.modal', { timeout: 15000 }); await p.waitForTimeout(400); await shot(p, '05-quiz');
  await p.click('.modal [data-i="1"]'); await p.waitForTimeout(600); await shot(p, '05b-quiz-answer');
  await p.click('.modal .btn');
  await p.click('[data-act=daily]').catch(()=>{});
  await p.goto('https://app.test/'); await p.waitForTimeout(800);
  await p.click('.burger'); await p.waitForTimeout(300); await p.click('#drawer [data-go=face]'); await p.waitForTimeout(500);
  await shot(p, '06a-atlas'); await p.screenshot({ path: path.join(out, '06a-atlas-full.png'), fullPage: true });
  await p.click('[data-expr=sad]'); await p.waitForTimeout(1600); await shot(p, '06c-expr-detail');
  await p.click('#ex-close'); await p.click('[data-ftab=train]'); await p.waitForTimeout(300);
  await p.evaluate(() => { FACE_LEVELS[0].ms = 6000; });
  await p.click('[data-act=face-go]'); await p.waitForTimeout(3000); await shot(p, '06-face-flash');
  await p.evaluate(() => { const b = [...document.querySelectorAll('#opts .opt')].find(x => x.dataset.e === Face.cur); Face.state = 'answer'; Face.answer(Face.cur, b); });
  await p.waitForTimeout(1500); await shot(p, '06b-face-answer');
  await p.click('.burger'); await p.waitForTimeout(300); await p.click('#drawer [data-go=money]'); await p.waitForTimeout(400); await shot(p, '07-money');
  await p.click('.burger'); await p.waitForTimeout(300); await p.click('#drawer [data-go=breath]'); await p.waitForTimeout(300); await p.click('[data-br="1"]'); await p.waitForTimeout(1500); await shot(p, '08-breath');
  await p.click('.burger'); await p.waitForTimeout(300); await p.click('#drawer [data-go=coach]'); await p.waitForTimeout(300);
  await p.fill('#askq', 'איך להתחיל לחסוך?'); await p.click('#asks'); await p.waitForTimeout(1200); await shot(p, '09-coach');
  await p.click('[data-mode=rp]'); await p.click('[data-rp=raise]'); await p.waitForTimeout(400);
  await p.fill('#rpq', 'הבאתי שלושה לקוחות השנה ואני מבקש העלאה.'); await p.click('#rps'); await p.waitForTimeout(700);
  await p.fill('#rpq', 'אני מבקש 12 אחוז.'); await p.click('#rps'); await p.waitForTimeout(700);
  await p.click('[data-act=rp-end]'); await p.waitForTimeout(1200); await shot(p, '10-roleplay');
  const fx = await p.evaluate(() => ({ xp: S.xp, lvl: levelOf(), quiz: S.quiz, face: S.face, mem: S.memory, spoken: window.__spoken.length, saved: !!window.__saved }));
  console.log(JSON.stringify(fx));
  await p.click('.top [data-go=home]'); await p.waitForTimeout(300);
  await p.evaluate(() => act('daily', document.body)); await p.waitForTimeout(500); await shot(p, '11-player');
  console.log('errors', errs);
  await b.close();
})();
